#!/usr/bin/env python3
"""Generates lib/import/legacy_codepage_tables.dart.

Windows desktop apps such as MobaXterm save their settings in the ANSI code
page of the machine: GBK (CP936) on Chinese Windows and Shift_JIS (CP932) on
Japanese Windows. Dart has no decoder for either, so the double-byte tables
are generated from Python's codecs and checked in.

Each table is one string indexed by (lead - firstLead) * 192 + (trail - 0x40)
for trail bytes 0x40..0xFF. Unmapped pairs and pairs that decode to private
use code points are U+FFFD, which the decoder treats as invalid.

Run from apps/client:  python3 tool/gen_legacy_codepage_tables.py
"""

from pathlib import Path

TRAIL_FIRST = 0x40
TRAIL_COUNT = 0x100 - TRAIL_FIRST  # 192
HOLE = "�"


def table(codec, leads):
    chars = []
    for lead in leads:
        for trail in range(TRAIL_FIRST, 0x100):
            try:
                text = bytes([lead, trail]).decode(codec)
            except UnicodeDecodeError:
                text = HOLE
            if len(text) != 1 or 0xE000 <= ord(text) <= 0xF8FF:
                text = HOLE
            chars.append(text)
    return "".join(chars)


def single_table(codec):
    chars = []
    for byte in range(0x80, 0x100):
        try:
            text = bytes([byte]).decode(codec)
        except UnicodeDecodeError:
            text = HOLE
        chars.append(text)
    return "".join(chars)


def dart_literal(text, width=76):
    out = []
    line = ""
    for ch in text:
        if ch == "\\":
            piece = "\\\\"
        elif ch == "'":
            piece = "\\'"
        elif ch == "$":
            piece = "\\$"
        elif ord(ch) < 0x20 or 0x7F <= ord(ch) < 0xA0 or ch in "  ﻿":
            piece = "\\u{%X}" % ord(ch)
        else:
            piece = ch
        if len(line) + len(piece) > width:
            out.append("    '" + line + "'")
            line = ""
        line += piece
    if line:
        out.append("    '" + line + "'")
    return "\n".join(out)


def main():
    gbk_leads = range(0x81, 0xFF)
    cp932_leads = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
    gbk = table("gbk", gbk_leads)
    cp932 = table("cp932", cp932_leads)
    assert len(gbk) == len(gbk_leads) * TRAIL_COUNT
    assert len(cp932) == len(cp932_leads) * TRAIL_COUNT
    cp1251 = single_table("cp1251")
    cp1252 = single_table("cp1252")
    body = f"""// GENERATED by tool/gen_legacy_codepage_tables.py. Do not edit by hand.
// ignore_for_file: lines_longer_than_80_chars

/// Trail bytes covered by each double-byte table row (0x40..0xFF).
const legacyTrailFirst = 0x{TRAIL_FIRST:02X};
const legacyTrailCount = {TRAIL_COUNT};

/// GBK / Windows code page 936, lead bytes 0x81..0xFE.
const gbkLeadFirst = 0x81;
const gbkLeadLast = 0xFE;
const gbkTable =
{dart_literal(gbk)};

/// Shift_JIS / Windows code page 932, lead bytes 0x81..0x9F and 0xE0..0xFC
/// (rows for 0xE0.. follow the 31 rows of 0x81..0x9F).
const cp932Table =
{dart_literal(cp932)};

/// Windows-1251 (Cyrillic) bytes 0x80..0xFF.
const cp1251High =
{dart_literal(cp1251)};

/// Windows-1252 (Western) bytes 0x80..0xFF.
const cp1252High =
{dart_literal(cp1252)};
"""
    target = Path(__file__).resolve().parent.parent / "lib/import/legacy_codepage_tables.dart"
    target.write_text(body, encoding="utf-8")
    print(target, len(gbk), len(cp932), target.stat().st_size)


if __name__ == "__main__":
    main()
